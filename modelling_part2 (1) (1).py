# -----------------------------------------------------------
X_features = np.concatenate([
    X_combined_embed,              # semantic text info
    X_addr_embed,                  # address embeddings
    df[['Fraud_Risk_Score',        # numeric risk score
        'Gender_encoded',
        'DocType_encoded',
        'DocNum_length',
        'DocNum_digits',
        'DocNum_uppercase']].values
], axis=1)

# Normalize all features
