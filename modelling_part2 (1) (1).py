# Encode categorical fields (gender, document type)
le_gender = LabelEncoder()
le_doc = LabelEncoder()
df['Gender_encoded'] = le_gender.fit_transform(df['Gender_clean'])
df['DocType_encoded'] = le_doc.fit_transform(df['Document_type_clean'])

